import type { DesignDocument, RenderOptions, Style } from "./model";
import { cssName, escapeHTML, webGenerator } from "./web";

const slug = (name: string) =>
  name
    .normalize("NFKD")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 64)
    .replace(/-+$/, "");

const declarations = (style: Style) =>
  Object.entries(style)
    .map(([property, value]) => `  ${cssName(property)}: ${value};`)
    .join("\n");

// A closing style tag is interpreted by HTML even inside a quoted CSS value.
const protectRawStyle = (css: string) => css.replace(/</g, "\\3c ");

const supportedGoogleFonts = new Set([
  "DM Sans",
  "Inter",
  "Lato",
  "Montserrat",
  "Nunito",
  "Open Sans",
  "Poppins",
  "Roboto",
  "Roboto Mono",
  "Source Sans 3",
]);

function googleFontLinks(document: DesignDocument): string[] {
  const fonts = new Set<string>();
  const nodes = [...document.roots];
  while (nodes.length) {
    const node = nodes.pop()!;
    const family = /^"([^"]+)"/.exec(
      node.visual.textMetrics?.fontFamily ?? "",
    )?.[1];
    if (family && supportedGoogleFonts.has(family)) fonts.add(family);
    nodes.push(...node.children);
  }
  if (!fonts.size) return [];
  const query = [...fonts]
    .sort()
    .map(
      (family) => `family=${encodeURIComponent(family).replace(/%20/g, "+")}`,
    )
    .join("&amp;");
  return [
    `  <link rel="stylesheet" href="https://fonts.googleapis.com/css2?${query}&amp;display=swap">`,
  ];
}

export class SingleFileHtmlEmitter {
  constructor(
    private readonly generatedAt = new Date(),
    private readonly linkFonts = false,
  ) {}

  emit(
    document: DesignDocument,
    options: RenderOptions,
    stylesheet?: "styles.css",
  ) {
    const title =
      document.roots.length === 1 ? document.roots[0].name : "Figma selection";
    const date = this.generatedAt.toISOString().slice(0, 10);
    const block = slug(title) || "design";
    const classes = new Map<string, string>();
    const names = new Set<string>();
    const rules: string[] = [];
    const markup = webGenerator({
      initialDepth: 1,
      classFor: (node, style) => {
        const declarationsText = declarations(style);
        const existing = classes.get(declarationsText);
        if (existing) return existing;

        const element = slug(node.name) || node.tag;
        const base = `figma-${block}${element === block ? "" : `__${element}`}`;
        let name = base;
        for (let suffix = 2; names.has(name); suffix++)
          name = `${base}--${suffix}`;
        names.add(name);
        classes.set(declarationsText, name);
        rules.push(`.${name} {\n${declarationsText}\n}`);
        return name;
      },
    }).render(document, options);
    const css = [
      "*, *::before, *::after { box-sizing: border-box; }",
      "body { margin: 0; font-family: system-ui, sans-serif; }",
      "img { display: block; max-width: 100%; }",
      `:root {\n${declarations(document.tokens)}\n}`,
      ...rules,
    ].join("\n\n");
    const commentTitle = title.replace(/-/g, "–").replace(/[\r\n]+/g, " ");
    return {
      css,
      markup,
      html: [
        "<!DOCTYPE html>",
        `<!-- Generated by Figma to Code | ${escapeHTML(commentTitle)} | ${date} -->`,
        '<html lang="en">',
        "<head>",
        '  <meta charset="utf-8">',
        '  <meta name="viewport" content="width=device-width, initial-scale=1">',
        `  <title>${escapeHTML(title)}</title>`,
        ...(this.linkFonts ? googleFontLinks(document) : []),
        stylesheet
          ? `  <link rel="stylesheet" href="${stylesheet}">`
          : `  <style>\n${protectRawStyle(css)
              .split("\n")
              .map((line) => line && `    ${line}`)
              .join("\n")}\n  </style>`,
        "</head>",
        "<body>",
        markup
          .split("\n")
          .map((line) => `  ${line}`)
          .join("\n"),
        "</body>",
        "</html>",
        "",
      ].join("\n"),
    };
  }

  render(document: DesignDocument, options: RenderOptions): string {
    return this.emit(document, options).html;
  }
}
